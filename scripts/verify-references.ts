/**
 * Verify every DOI in content/references.yaml against Crossref.
 *
 *   npm run verify-refs
 *
 * For each reference with a DOI, it fetches the Crossref record and compares
 * title, year, journal and first-author surname. It writes
 * reports/reference-verification.md and exits non-zero on any mismatch or
 * unresolvable DOI. References without a DOI (books, standards, web pages)
 * are listed for manual checking.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { load } from 'js-yaml';

interface Ref {
  key: string;
  type: string;
  authors: string;
  year: number;
  title: string;
  container?: string;
  volume?: number | string;
  issue?: number | string;
  pages?: string;
  doi?: string;
  url?: string;
}

const file = load(readFileSync('content/references.yaml', 'utf8')) as { references: Ref[] };

const norm = (s: string) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/<[^>]+>/g, '')
    .replace(/[^a-z0-9 ]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

function similarity(a: string, b: string) {
  const A = new Set(norm(a).split(' ').filter((w) => w.length > 2));
  const B = new Set(norm(b).split(' ').filter((w) => w.length > 2));
  if (!A.size || !B.size) return 0;
  let inter = 0;
  A.forEach((w) => B.has(w) && inter++);
  return inter / Math.min(A.size, B.size);
}

const firstSurname = (authors: string) => norm(authors.split(',')[0]).split(' ').pop() ?? '';

async function fetchCrossref(doi: string) {
  const url = `https://api.crossref.org/works/${encodeURIComponent(doi)}`;
  for (let attempt = 0; attempt < 3; attempt++) {
    const res = await fetch(url, { headers: { 'User-Agent': 'nd-test-reference-checker/0.1' } });
    if (res.status === 404) return null;
    if (res.ok) return ((await res.json()) as { message: any }).message;
    await new Promise((r) => setTimeout(r, 1000 * (attempt + 1)));
  }
  throw new Error(`Crossref request failed for ${doi}`);
}

const rows: string[] = [];
const problems: string[] = [];
const manual: Ref[] = [];

for (const ref of file.references) {
  if (!ref.doi) {
    manual.push(ref);
    continue;
  }
  let msg: any;
  try {
    msg = await fetchCrossref(ref.doi);
  } catch (e) {
    problems.push(`${ref.key}: ${(e as Error).message}`);
    rows.push(`| ${ref.key} | ${ref.doi} | ERROR | request failed |`);
    continue;
  }
  if (!msg) {
    problems.push(`${ref.key}: DOI not found (${ref.doi})`);
    rows.push(`| ${ref.key} | ${ref.doi} | FAIL | DOI not found |`);
    continue;
  }
  const cTitle: string = [msg.title?.[0], msg.subtitle?.[0]].filter(Boolean).join(': ');
  const cYear: number | undefined = (msg['published-print'] ?? msg['published-online'] ?? msg.issued)?.['date-parts']?.[0]?.[0];
  const cYearIssued: number | undefined = msg.issued?.['date-parts']?.[0]?.[0];
  const cContainer: string = msg['container-title']?.[0] ?? '';
  const cFirst: string = norm(msg.author?.[0]?.family ?? msg.author?.[0]?.name ?? '');

  const issues: string[] = [];
  const tSim = similarity(ref.title, cTitle);
  if (tSim < 0.6) issues.push(`title differs ("${cTitle}")`);
  if (cYear && ref.year !== cYear && ref.year !== cYearIssued) issues.push(`year ${ref.year} vs Crossref ${cYear}`);
  if (ref.type === 'article' && ref.container && cContainer && similarity(ref.container, cContainer) < 0.5)
    issues.push(`journal "${cContainer}"`);
  const mySurname = firstSurname(ref.authors);
  if (cFirst && mySurname && !cFirst.includes(mySurname) && !mySurname.includes(cFirst))
    issues.push(`first author "${msg.author?.[0]?.family}"`);
  if (ref.volume && msg.volume && String(ref.volume) !== String(msg.volume)) issues.push(`volume ${msg.volume}`);
  if (ref.pages && msg.page && norm(String(ref.pages)) !== norm(String(msg.page)).replace(/ /g, ' '))
    issues.push(`pages ${msg.page}`);

  const status = issues.length ? 'CHECK' : 'OK';
  if (issues.length) problems.push(`${ref.key}: ${issues.join('; ')}`);
  rows.push(`| ${ref.key} | ${ref.doi} | ${status} | ${issues.join('; ') || `${cContainer} (${cYear})`} |`);
}

const today = new Date().toISOString().slice(0, 10);
const md = `# Reference verification report

Generated by \`npm run verify-refs\` on ${today}. Source: Crossref REST API.

- References with DOI: ${file.references.length - manual.length}
- Verified OK: ${rows.filter((r) => r.includes('| OK |')).length}
- Needing attention: ${problems.length}
- No DOI (manual check): ${manual.length}

| Key | DOI | Status | Crossref match / issue |
|---|---|---|---|
${rows.join('\n')}

## References without a DOI (check manually)

${manual.map((r) => `- **${r.key}**: ${r.authors} (${r.year}). *${r.title}*. ${r.url ?? ''}`).join('\n')}
`;
mkdirSync('reports', { recursive: true });
writeFileSync('reports/reference-verification.md', md);

console.log(md.split('\n').slice(0, 9).join('\n'));
if (problems.length) {
  console.log('\nIssues:\n- ' + problems.join('\n- '));
  process.exit(1);
}
console.log('\nAll DOIs verified.');
